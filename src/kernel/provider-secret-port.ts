/**
 * 厂商密钥的窄读口（kernel）。
 *
 * 密钥躺在 **api 属主**表里，而用它的是内容域的文本 / 图片 / 对象存储出口。
 * 与本批其余端口不同的是：**这条只在启动期被调几次**（每个厂商一次），不在任何热路径上，
 * 所以它可以就是一个普通的异步跨进程读，不需要镜像。
 *
 * **明文的处置纪律照旧、且跨进程后更要紧**：
 * 取回的明文只用于构造出口客户端，MUST NOT 日志化、MUST NOT 回传前端、MUST NOT 落盘。
 *
 * **读不到 ≠ 空字符串。** 缺凭据返回 `null`，调用方据此走「未配置」那条路
 * （既有行为：不构造该出口 / 回落 env）。返回 `''` 会让调用方以为配了一个空密钥，
 * 于是构造出一个必然 401 的客户端 —— 那是把「没配」洗成「配错了」。
 */

export interface ProviderSecretReader {
  /**
   * 读某个厂商的某个凭据字段。缺 → `null`。
   * 实现方**绝不**因为读失败就返回 `null`：读失败要抛，让调用方能区分「没配」与「读不到」。
   */
  getSecretForRuntime(provider: string, field: string): Promise<string | null>;
}
